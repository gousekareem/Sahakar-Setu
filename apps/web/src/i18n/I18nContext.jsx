const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(localStorage.getItem("sahakarsetu_lang") || "en");

  const changeLang = useCallback((code) => {
    localStorage.setItem("sahakarsetu_lang", code);
    setLang(code);
  }, []);

  const t = useCallback((key) => dict[lang]?.[key] || dict.en[key] || key, [lang]);

  return <I18nContext.Provider value={{ lang, changeLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
